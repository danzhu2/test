#ifndef __REMOTE_H
#define __REMOTE_H

/* ============================================================================
 *  遥控小车 —— 对应拓展 6.3（遥控小车，10 分）
 *
 *  方案：蓝牙透传模块（HC-05 / JDY-31）接 USART1（和上位机共用一条串口线），
 *        手机端用"蓝牙串口助手"App 发指令 = 上位机遥控，硬件零成本。
 *        ⚠️【需修改】蓝牙模块波特率必须与 SERIAL_BAUD 一致（HC-05 默认 9600，
 *           需要用 AT 命令改成 115200，或改 serial.h 的 SERIAL_BAUD）。
 *
 *  指令（一行一条，串口助手/手机 App 发送）：
 *    FWD   前进        BACK  后退
 *    LEFT  左转        RIGHT 右转
 *    STOP  停止
 *
 *  收到指令后回传 "STATE:XXX"，供上位机显示当前运动状态（6.3 的 3 分）。
 * ==========================================================================*/

/* 处理一条遥控指令（由 serial.c 的指令解析器路由过来）。
 * 巡线运行中遥控指令一律忽略，两者互斥，防止打架。 */
void Remote_Handle(const char *cmd);

/* 停车/进入巡线时调用：清掉遥控保持的输出状态 */
void Remote_Reset(void);

/* 当前运动状态字符串（"IDLE"/"FWD"/"BACK"/"LEFT"/"RIGHT"/"STOP"），
 * 供上位机查询显示 */
const char *Remote_GetState(void);

#endif
