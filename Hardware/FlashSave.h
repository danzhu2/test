#ifndef __FLASHSAVE_H
#define __FLASHSAVE_H

#include "stm32f10x.h"

/* ============================================================================
 *  【新增文件】参数掉电保存 —— 对应拓展 6.2（参数设置与掉电保存，5 分）
 *
 *  原理：STM32 的 Flash 掉电不丢失，把参数写到"程序用不到的最后一页"，
 *        上电时读出来用。注意两件事：
 *   1. C8T6 是中容量（64KB，每页 1KB）。最后一页地址 = 0x08000000 + 64K - 1K
 *      = 0x0800FC00。⚠️【需修改】换 HD 容量芯片（页 2KB）要改地址和擦除方式。
 *   2. Flash 写入最小单位是"半字（16 位）"，且必须先整页擦除（全变 0xFFFF），
 *      所以"改一个参数 = 擦一页 + 重写整页"。
 *
 *  ⚠️【易错】擦除一页约 20~40ms，期间 CPU 停顿、Tick 中断会延迟。
 *     所以绝不要在巡线运行中保存参数！本工程把保存动作放在"拓展页按 K4
 *     退出参数编辑时"，此时小车一定是停着的。
 * ==========================================================================*/

/* 所有需要掉电保存的参数集中在一个结构体里，以后加参数只改这里 */
typedef struct
{
	uint32_t magic;			/* 魔数：判断 Flash 里存的是不是本工程的有效数据 */
	int16_t  baseSpeed;		/* 基础速度（PWM 千分比，0~1000），影响巡线与遥控 */
	int16_t  targetLaps;	/* 目标圈数（发车后跑几圈停车） */
	int16_t  kp;			/* 转向环 Kp，实际值 = 存储值 / 100（避免浮点存储） */
	int16_t  ki;			/* 转向环 Ki，同上 */
	int16_t  kd;			/* 转向环 Kd，同上 */
	int16_t  reserve;		/* 预留：凑成 16 字节，以后加参数从这里拿，避免改布局 */
} Params_t;

extern Params_t g_params;

/* 上电调用一次：Flash 有有效数据 → 载入；没有 → 载入默认值 */
void Params_Load(void);

/* 把 g_params 写入 Flash（擦一页 + 重写 + 回读校验）。调用时小车必须处于停止状态。
 * 返回 1 = 校验通过；0 = 没存上（上层应提示用户重试，别让用户以为存上了） */
uint8_t Params_Save(void);

#endif
