#ifndef __ENCODER_H
#define __ENCODER_H

#include "stm32f10x.h"

/* ============================================================================
 *  电机编码器测速（定时器编码器接口模式）—— 拓展 6.4 PID 闭环的前提
 *
 *  硬件：带 AB 相霍尔编码器的减速电机（GA25/N20 等）。
 *    左电机 A/B 相 → PB4/PB5（TIM3_CH1/CH2，⚠️ 已从默认 PA6/PA7 重映射，
 *                     因为 PA0~PA7 全部让给了 8 路灰度传感器）
 *    右电机 A/B 相 → PB6/PB7（TIM4_CH1/CH2，无需重映射）
 *    ⚠️【需修改】AB 相接反只会导致计数值方向反，跑一次测速就能看出来，
 *       把 .c 里对应的 INVERT 宏改 1 即可，不用换线。
 *
 *  ⚠️【依赖】PB4/PB5 上电默认是 JTAG 引脚，必须先在 main() 里执行
 *     GPIO_Remap_SWJ_JTAGDisable + GPIO_PartialRemap_TIM3 两句重映射，
 *     否则编码器计数完全不动（编译不报错，实物调试大坑）。SWD 下载不受影响。
 *
 *  原理：定时器编码器模式让硬件自动计数正交脉冲，转向决定加减计数，
 *        不占用 CPU。每隔固定时间读一次计数值，差值就正比于这段时间的转速。
 * ==========================================================================*/

void Encoder_Init(void);

/* 读取"自上次调用以来"的计数值增量并清零。    //是读取电机的正反转，控制还是在电机实现
 * 正值 = 正转（前进），负值 = 反转。两次调用间隔越固定，速度值越稳定。 */
int16_t Encoder_GetLeft(void);
int16_t Encoder_GetRight(void);

#endif
