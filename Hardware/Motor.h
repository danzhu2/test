#ifndef __MOTOR_H
#define __MOTOR_H

#include "stm32f10x.h"

/* ============================================================================
 * 直流电机驱动（TB6612 + 定时器 PWM）—— 巡线小车执行器的底层        //通过点击正反转控制前后，占空比控制单轮速度左右转
 *
 *  硬件：
 *    TB6612FNG 双路驱动。PWMA/PWMB 接 PWM，AIN1/AIN2、BIN1/BIN2 是方向脚，
 *    STBY 接高电平使能。真值表：AIN1=1,AIN2=0 正转；AIN1=0,AIN2=1 反转；
 *    两个都 0 → 滑行；两个都 1 → 短路刹车。
 *
 *  ⚠️【需修改】所有引脚宏见 Motor.c 顶部，接线不同改宏即可。
 *     特别注意：TIM1 是高级定时器，必须开 MOE（.c 里已写），换到
 *     TIM2/TIM3 做普通 PWM 时要把那行删掉。
 * ==========================================================================*/

void Motor_Init(void);

/* 设置两轮速度：范围 -1000 ~ +1000（正 = 前进），单位是"千分之一满占空比"。
 * 用 1000 而不是 0~720 这种原始计数值，是为了上层算法不用关心 PWM 硬件细节。 */
void Motor_Set(int16_t left, int16_t right);

/* 短路刹车：TB6612 两方向脚同时置 1，电机两端被短接，惯性立刻被吃掉。
 * 巡线停车必须用它——只把 PWM 降到 0 是滑行，会冲出停车线。 */
void Motor_Brake(void);

#endif
