#ifndef __BUZZER_H
#define __BUZZER_H

#include "stm32f10x.h"

/* ============================================================================
 *  有源蜂鸣器 —— 对应赛题第 4 项 b（发车蜂鸣一声）、c（计圈蜂鸣）
 *
 *  硬件：有源蜂鸣器（通电就响，不用 PWM 驱动），经 NPN 三极管放大，
 *        IO 输出高电平 → 三极管导通 → 蜂鸣器响。
 *
 *  ⚠️【需修改】BUZZER_GPIO_PIN / PORT：按你实际接线改，默认 PB3。
 *     PB3 是 JTAG 引脚，必须等 main() 里的"禁 JTAG"执行后再初始化本模块，
 *     否则写 IO 无效。SWD 下载调试不受影响。
 * ==========================================================================*/

/* 发一声 / 发 N 声（非阻塞：只登记需求，真正翻转由 Buzzer_Task() 在主循环里做） */
void Buzzer_Beep(uint8_t times, uint16_t onMs);

/* 主循环里反复调用。不响的时候一次判断就返回，几乎不花时间 */
void Buzzer_Task(void);

#endif
