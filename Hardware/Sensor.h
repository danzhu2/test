#ifndef __SENSOR_H
#define __SENSOR_H

#include "stm32f10x.h"

/* ============================================================================
 * 8 路灰度巡线传感器 —— 对应赛题第 4 项 a（传感器数据显示）
 *                                    以及 4b/4c/4d/4e 的巡线控制输入
 *
 *  硬件：8 路红外/灰度巡线模块（数字量输出型，板载比较器，如 TCRT5000 排）。
 *        ⚠️【需修改】如果你的模块是模拟量输出（AO），这个文件要改成 ADC+DMA 采样，
 *           并加"标定阈值 → 数字化"一层。买模块时认准有 DO 数字输出的型号。
 *
 *  编号约定：S1 = 最左，S8 = 最右（从小车前进方向看）。
 * ==========================================================================*/

/* ⚠️【需修改】传感器压线时的电平。
 *   大多数比较器输出模块：压黑线 → 输出低电平；白底 → 输出高电平。
 *   个别模块相反。上电后在黑线上放一下车看 OLED 显示（Menu 巡线页）即可判断：
 *   压线那一路显示 1 才是正确极性，反了就把这个宏改成 0。 */
#define SENSOR_LINE_LEVEL		0		/* 压线(黑)时引脚电平：0=低有效, 1=高有效 */

/* ⚠️【需修改】传感器 8 个 IO 所在端口：默认全在 GPIOA（PA0~PA7）。
 *   如果接线分在两个端口，把 Sensor_Read() 里改成两次 GPIO_ReadInputDataBit。 */
#define SENSOR_GPIO_PORT		GPIOA

/* 读取全部 8 路：bit0 = S1(最左) ... bit7 = S8(最右)，压线的那一位 = 1 */
uint8_t Sensor_Read(void);

/* 加权误差：压线位置相对赛道中心的偏差，单位"半格"，正值 = 线在右侧。
 * 中心(S4/S5 之间) = 0；线跑到了小车右边 → 误差为正 → 应该右转。
 * 全部丢线时返回 0.0f（此时误差无意义，LineFollow 会走"记忆寻线"分支）；
 * 全部压线（十字/起点横杠）时算出来也是 0，恰好对应"直行通过"策略。 */
float Sensor_GetError(void);

/* 压线的传感器数量（0 = 全丢线；8 = 全压线，通常是十字或起点横杠） */
uint8_t Sensor_CountOn(void);

#endif
